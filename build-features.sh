#!/usr/bin/env bash
# Builds the "AquaRev Advantage" features section (replaces Webflow Section 7).
#
#   AquaRev_Features.html  →  features.css / features.js / webflow-embed-features.html / preview-features.html
#
# Same pattern as build.sh: the markup (logo list) is pasted into Webflow so it is real HTML; CSS, JS and
# the logo files (logos/, made by src/make_logos.py) are hosted on GitHub Pages next to the hero.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
MASTER="$HERE/AquaRev_Features.html"
PAGES="https://jeffatley-web.github.io/aquarev_home_hero"
STAMP="$(date +%Y%m%d%H%M)"

cd "$HERE"

{
  echo "/* AquaRev features section. Generated by build-features.sh from AquaRev_Features.html; do not edit by hand. */"
  awk '/^<style>$/{f=1;next} /^<\/style>$/{f=0} f' "$MASTER" | sed -e '/preview page only/,$d'
} > features.css

{
  echo "/* AquaRev features section. Generated by build-features.sh from AquaRev_Features.html; do not edit by hand. */"
  awk '/^<script>$/{f=1;next} /^<\/script>$/{f=0} f' "$MASTER"
} > features.js

markup() {
  awk '/^<section id="arfx"/{f=1} f{print} f&&/^<\/section>$/{exit}' "$MASTER" \
  | cat
}

{
  cat <<EOF
<!-- AquaRev "AquaRev Advantage" features section (#arfx). Paste this whole block into one Webflow Embed element placed
     directly under the logo marquee embed. Generated by build-features.sh; CSS, JS and logos are on GitHub Pages. -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=Manrope:wght@600;700;800&display=swap">
<link rel="stylesheet" href="$PAGES/features.css?v=$STAMP">
EOF
  markup "$PAGES/"
  echo "<script defer src=\"$PAGES/features.js?v=$STAMP\"></script>"
} > webflow-embed-features.html

{
  cat <<EOF
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Preview: AquaRev hero + features section (local, mirrors the Webflow embeds)</title>
<style>
body{margin:0;background:#040f1e;font-family:Arial,sans-serif}
.w-nav{position:sticky;top:0;z-index:10;height:103px;background:#040f1e;color:#fff;display:flex;align-items:center;justify-content:space-between;padding:0 32px;font:600 14px Arial,sans-serif}
.w-nav b{padding:12px 18px;border-radius:10px;background:#0000ff}
.next{padding:80px 32px;min-height:60vh;color:#fff}
@media (max-width:767px){.w-nav{height:72px;padding:0 16px}}
</style>
</head>
<body>
<div class="w-nav">AquaRev Water (site nav stand-in)<b>ROI Assessment</b></div>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=Manrope:wght@600;700;800&display=swap">
<link rel="stylesheet" href="home-hero.css">
EOF
  awk '/^<section id="arhh"/{f=1} f{print} f&&/^<\/section>$/{exit}' AquaRev_Home_Hero.html
  echo '<script defer src="home-hero.js"></script>'
  echo '<link rel="stylesheet" href="logo-marquee.css">'
  awk '/^<section id="arlm"/{f=1} f{print} f&&/^<\/section>$/{exit}' AquaRev_Logo_Marquee.html
  echo '<script defer src="logo-marquee.js"></script>'
  echo '<link rel="stylesheet" href="features.css">'
  markup ""
  cat <<EOF
<section class="next"><h2>Testimonials (next section)</h2></section>
<script defer src="features.js"></script>
</body>
</html>
EOF
} > preview-features.html

wc -c features.css features.js webflow-embed-features.html
