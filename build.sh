#!/usr/bin/env bash
# Builds the aquarevwater.us home page hero from the master in this folder.
# Re-run after any change to AquaRev_Home_Hero.html, then push.
#
#   AquaRev_Home_Hero.html  →  home-hero.css / home-hero.js / webflow-embed-home-hero.html / preview.html
#
# Unlike the other pages, the hero's markup goes straight into the Webflow embed (not injected by JS),
# so the H1, copy and CTA are in the page HTML for search engines and paint without waiting for a script.
# CSS (already scoped under #arhh in the master), JS, video, posters and badges are hosted on GitHub Pages.
# Changing hero copy therefore means re-pasting the embed; style and behaviour changes only need a push.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
MASTER="$HERE/AquaRev_Home_Hero.html"
PAGES="https://jeffatley-web.github.io/aquarev_home_hero"
STAMP="$(date +%Y%m%d%H%M)"
FONTS='https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=Manrope:wght@600;700;800&display=swap'

cd "$HERE"

# master <style> without the preview-only body rule
{
  echo "/* AquaRev home hero. Generated by build.sh from AquaRev_Home_Hero.html; do not edit by hand. */"
  awk '/^<style>$/{f=1;next} /^<\/style>$/{f=0} f' "$MASTER" | sed -e '/preview page only/,$d'
} > home-hero.css

{
  echo "/* AquaRev home hero. Generated by build.sh from AquaRev_Home_Hero.html; do not edit by hand. */"
  awk '/^<script>$/{f=1;next} /^<\/script>$/{f=0} f' "$MASTER"
} > home-hero.js

# the <section id="arhh"> … </section> block, with local paths pointed at GitHub Pages
markup() {
  awk '/^<section id="arhh"/{f=1} f{print} f&&/^<\/section>$/{exit}' "$MASTER" \
  | sed -E -e "s#(src|srcset|data-desktop|data-mobile)=\"(media|img)/#\1=\"$1\2/#g"
}

{
  cat <<EOF
<!-- AquaRev home page hero (#arhh). Paste this whole block into one Webflow Embed element that replaces the
     old hero section. Generated by build.sh; CSS, JS and media are on GitHub Pages. Bump nothing by hand. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="$PAGES/home-hero.css?v=$STAMP">
EOF
  markup "$PAGES/"
  echo "<script defer src=\"$PAGES/home-hero.js?v=$STAMP\"></script>"
} > webflow-embed-home-hero.html

# local preview: a stand-in for the site's 103 px sticky nav and the next section, so the fit can be checked
{
  cat <<EOF
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Preview: AquaRev home hero (local, mirrors the Webflow embed)</title>
<style>
body{margin:0;background:#fff;font-family:Arial,sans-serif}
.w-nav{position:sticky;top:0;z-index:10;height:103px;background:#040f1e;color:#fff;display:flex;align-items:center;justify-content:space-between;padding:0 32px;font:600 14px Arial,sans-serif}
.w-nav b{padding:12px 18px;border-radius:10px;background:#0000ff}
.next{padding:80px 32px;min-height:60vh;background:#f4f7fb;color:#0b1d33}
@media (max-width:767px){.w-nav{height:72px;padding:0 16px}}
</style>
</head>
<body>
<div class="w-nav">AquaRev Water (site nav stand-in)<b>ROI Assessment</b></div>
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="home-hero.css">
EOF
  markup ""
  cat <<EOF
<section class="next"><h2>Next section</h2><p>Checks that the hero hands off cleanly to the rest of the home page.</p></section>
<script defer src="home-hero.js"></script>
</body>
</html>
EOF
} > preview.html

wc -c home-hero.css home-hero.js webflow-embed-home-hero.html
du -ch media/* img/* | tail -1
